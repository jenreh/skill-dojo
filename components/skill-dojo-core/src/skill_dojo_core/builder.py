log = logging.getLogger(__name__)

PLUGINS_DIR = "plugins"
FLAT_SKILLS_DIR = "skills"
ROOT_MANIFEST = "plugin.json"
CLAUDE_MANIFEST = ".claude-plugin/plugin.json"
ROOT_MCP = "mcp.json"
CLAUDE_MCP = ".mcp.json"
OPENAI = "com.openai"
MAX_SHORT = 64
PLUGIN_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
MCP_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json"


def plugin_dir(item_id: str) -> str:
    return f"{PLUGINS_DIR}/{item_id}"


def version_of(data: bytes | str | None) -> str | None:
    """``version`` of a manifest's JSON text, if it is a string."""
    if data is None:
        return None
    try:
        parsed = json.loads(data)
    except ValueError:
        return None
    version = parsed.get("version") if isinstance(parsed, dict) else None
    return version if isinstance(version, str) else None


def manifest_version(root: Path) -> str | None:
    """Version of the plugin in folder ``root``."""
    for rel in (ROOT_MANIFEST, CLAUDE_MANIFEST):
        try:
            version = version_of((root / rel).read_bytes())
        except OSError:
            continue
        if version:
            return version
    return None


def manifest_version_at(repo: Path, ref: str, item_id: str) -> str | None:
    """Version of plugin ``item_id`` as it is at ``ref``."""
    for rel in (ROOT_MANIFEST, CLAUDE_MANIFEST):
        version = version_of(git.show_file(repo, ref, f"{plugin_dir(item_id)}/{rel}"))
        if version:
            return version
    return None


def is_generated(rel: str, lock: ItemLock | None) -> bool:
    """Whether ``rel`` (inside a plugin) was generated by build, not upstream."""
    return lock is not None and rel in lock.generated


def display_name(name: str) -> str:
    return " ".join(part.capitalize() for part in name.split("-"))


def short_description(text: str) -> str:
    """First sentence of a description, cut to 64 characters."""
    sentence = re.split(r"(?<=[.!?])\s", text.strip(), maxsplit=1)[0].rstrip(".")
    if len(sentence) > MAX_SHORT:
        sentence = sentence[: MAX_SHORT - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return sentence


def registry_id(config: RegistryConfig, item: Item) -> str:
    return f"{config.name}:{item.id}"


def provenance(  # noqa: PLR0917
    config: RegistryConfig,
    policy: ChannelPolicy,
    item: Item,
    lock: ItemLock,
    manifest: dict[str, Any],
    skill: str | None = None,
) -> metadata.Provenance:
    """The provenance stamped into an item's manifest or one of its skills.

    A skill that is a part of a local plugin carries the upstream of its part.
    """
    upstream = lock.upstream
    source_path = f"{upstream.path}/skills/{skill}" if skill else None
    part = next(
        (p for p in lock.parts if skill and p.kind == "skill" and p.name == skill),
        None,
    )
    license_ = manifest.get("license")
    if part is not None:
        upstream, source_path = part.upstream, part.path
        license_ = upstream.license
    return metadata.Provenance(
        registry_id=registry_id(config, item),
        kind=item.kind.value,
        version=manifest.get("version"),
        upstream_marketplace=upstream.repository,
        upstream_plugin=upstream.plugin,
        upstream_ref=upstream.ref,
        upstream_commit=upstream.commit,
        upstream_version=lock.version,
        upstream_license=license_ if isinstance(license_, str) else None,
        source_path=source_path,
        source_digest=lock.tree_sha256,
        risk_tier=(item.risk_tier or policy.default_risk_tier).value,
        data_classification=item.data_classification
        or policy.default_data_classification,
        allowed_tools=item.allowed_tools or None,
        deprecation_replacement=item.deprecation.replacement
        if item.deprecation
        else None,
        deprecation_removal_date=item.deprecation.removal_date
        if item.deprecation
        else None,
        parts=[p.model_dump(by_alias=True) for p in lock.parts] or None,
    )


@dataclass
class PluginBuild:
    """Builds one plugin directory inside an overlay."""

    reg: Registry
    overlay: Overlay
    item: Item
    created: set[str] = field(default_factory=set)

    @property
    def base(self) -> str:
        return plugin_dir(self.item.id)

    @property
    def lock(self) -> ItemLock | None:
        return self.reg.lock.items.get(self.item.id)

    def rel(self, path: str) -> str:
        return f"{self.base}/{path}"

    def generated(self, path: str) -> bool:
        """Owned by build: generated earlier, in this run, or not there yet."""
        return (
            path in self.created
            or is_generated(path, self.lock)
            or not self.overlay.exists(self.rel(path))
        )

    def write(self, path: str, content: str | bytes) -> None:
        self.overlay.write(self.rel(path), content)
        self.created.add(path)

    def source_manifest(self) -> str:
        """The manifest path that holds real upstream content."""
        real = self.real_manifests()
        if real:
            return real[0]
        for path in (CLAUDE_MANIFEST, ROOT_MANIFEST):
            if self.overlay.read_text(self.rel(path)) is not None:
                return path
        raise InvalidInputError(
            f"{self.base}: no plugin.json or .claude-plugin/plugin.json"
        )

    def manifest_data(self) -> dict[str, Any]:
        text = self.overlay.read_text(self.rel(self.source_manifest()))
        try:
            data = json.loads(text or "")
        except json.JSONDecodeError as exc:
            raise InvalidInputError(f"{self.base}: invalid manifest: {exc}") from exc
        if not isinstance(data, dict):
            raise InvalidInputError(f"{self.base}: manifest must be a JSON object")
        return data

    def real_manifests(self) -> list[str]:
        return [
            path
            for path in (CLAUDE_MANIFEST, ROOT_MANIFEST)
            if self.overlay.exists(self.rel(path))
            and not self.overlay.is_link(self.rel(path))
            and not self.generated(path)
        ]

    def run(self) -> None:
        source = self.source_manifest()
        self.brand(source)
        for path in self.real_manifests() or [source]:
            self.stamp_manifest(path)
        other = ROOT_MANIFEST if source == CLAUDE_MANIFEST else CLAUDE_MANIFEST
        self.counterpart(source, other, self.reg.config.layout.manifest_symlinks)
        self.mcp()
        self.skills()

    def counterpart(self, source: str, other: str, use_link: bool) -> None:
        """Generate ``other`` from ``source`` when it is missing or generated."""
        if not self.generated(other):
            return
        if use_link:
            target = PurePosixPath(source)
            depth = len(PurePosixPath(other).parts) - 1
            self.overlay.link(
                self.rel(other), "/".join([".."] * depth + list(target.parts))
            )
            self.created.add(other)
            return
        text = self.overlay.read_text(self.rel(source)) or ""
        if other == ROOT_MANIFEST:
            text = with_schema(text)
        elif other == ROOT_MCP:
            text = with_schema(text, MCP_SCHEMA)
        self.write(other, text)

    def mcp(self) -> None:
        use_link = self.reg.config.layout.mcp_symlink
        for source, other in ((CLAUDE_MCP, ROOT_MCP), (ROOT_MCP, CLAUDE_MCP)):
            full = self.rel(source)
            if (
                self.overlay.exists(full)
                and not self.overlay.is_link(full)
                and not self.generated(source)
            ):
                self.counterpart(source, other, use_link)
                return

    def brand(self, source: str) -> None:
        branding = self.reg.config.branding
        if branding is None or self.item.kind is ItemKind.MIRROR:
            return
        full = self.rel(source)
        text = self.overlay.read_text(full) or ""
        data = self.manifest_data()
        ext = dict((data.get("extensions") or {}).get(OPENAI) or {})
        interface = dict(ext.get("interface") or {})
        description = str(data.get("description") or "")
        icon = self.icon_ref()
        defaults = {
            "displayName": display_name(self.item.id),
            "shortDescription": short_description(description),
            "longDescription": description,
            "developerName": branding.developer_name,
            "category": catalogs.category(
                catalogs.CatalogPlugin(self.item, data), self.reg.config
            ),
            "websiteURL": branding.website_url,
            "brandColor": branding.brand_color,
            "composerIcon": icon,
            "logo": icon,
        }
        for key, value in defaults.items():
            if value and key not in interface:
                interface[key] = value
        if ext.get("interface") != interface:
            ext["interface"] = interface
            self.relock_after(source, jsontext.set_extension(text, OPENAI, ext))
        if icon:
            self.copy_icon(f"assets/{PurePosixPath(icon).name}")

    def relock_after(self, path: str, text: str) -> None:
        """Write a tool-made change to a locked file and keep its lock current.

        Only when the file still matches its lock entry, so a hand edit is never
        absorbed into the lock.
        """
        lock = self.lock
        full = self.rel(path)
        before = self.overlay.read_text(full) or ""
        self.overlay.write(full, text)
        if lock is None or path not in lock.files:
            return
        ns = self.reg.config.namespace
        old = lock.files[path]
        was = hashing.file_lock_for(path, before.encode(), old.mode, ns)
        if hashing.drift({path: old}, {path: was}):
            return
        lock.files[path] = hashing.file_lock_for(path, text.encode(), old.mode, ns)
        lock.tree_sha256 = hashing.tree_sha256(lock.files)

    def icon_ref(self) -> str | None:
        branding = self.reg.config.branding
        if branding is None or branding.icon is None:
            return None
        return f"./assets/{PurePosixPath(branding.icon).name}"

    def copy_icon(self, path: str) -> None:
        branding = self.reg.config.branding
        if branding is None or branding.icon is None:
            return
        icon = self.reg.repo / branding.icon
        repo = self.reg.repo.resolve()
        if repo not in icon.resolve().parents:
            raise InvalidInputError(
                f"branding icon {branding.icon} is outside the repo"
            )
        if not icon.is_file():
            raise InvalidInputError(f"branding icon {branding.icon} not found")
        if self.generated(path):
            self.write(path, icon.read_bytes())

    def stamp_manifest(self, source: str) -> None:
        if self.lock is None:
            return
        full = self.rel(source)
        prov = provenance(
            self.reg.config,
            self.reg.policy,
            self.item,
            self.lock,
            self.manifest_data(),
        )
        text = self.overlay.read_text(full) or ""
        self.overlay.write(
            full, metadata.stamped_manifest(text, self.reg.config.namespace, prov)
        )

    def skill_names(self) -> list[str]:
        root = self.reg.repo / self.base / "skills"
        if root.is_symlink() or not root.is_dir():
            return []
        return sorted(
            p.name
            for p in root.iterdir()
            if p.is_dir() and not p.is_symlink() and (p / "SKILL.md").is_file()
        )

    def skills(self) -> None:
        manifest = self.manifest_data()
        for name in self.skill_names():
            skill_md = self.rel(f"skills/{name}/SKILL.md")
            text = self.overlay.read_text(skill_md) or ""
            if self.lock is not None and frontmatter.split(text) is not None:
                prov = provenance(
                    self.reg.config,
                    self.reg.policy,
                    self.item,
                    self.lock,
                    manifest,
                    skill=name,
                )
                text = metadata.stamped_skill(text, self.reg.config.namespace, prov)
                self.overlay.write(skill_md, text)
            self.openai_yaml(name, text)

    def openai_yaml(self, name: str, skill_text: str) -> None:
        branding = self.reg.config.branding
        if branding is None or not branding.openai_yaml_stubs:
            return
        path = f"skills/{name}/agents/openai.yaml"
        if self.generated(path):
            text = stub_yaml(name, skill_text, self.icon_ref(), branding.brand_color)
            self.write(path, text)
        else:
            text = self.overlay.read_text(self.rel(path)) or ""
        icon = self.icon_ref()
        if icon and icon in text:
            self.copy_icon(f"skills/{name}/assets/{PurePosixPath(icon).name}")


def with_schema(text: str, schema: str = PLUGIN_SCHEMA) -> str:
    """An Agent Plugins file needs ``$schema``; add it first when missing."""
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return text
    if not isinstance(data, dict) or "$schema" in data:
        return text
    return jsontext.dump({"$schema": schema, **data})


def quote(value: str) -> str:
    """A double-quoted YAML scalar (a JSON string is valid YAML)."""
    return json.dumps(value, ensure_ascii=False)


def stub_yaml(
    name: str, skill_text: str, icon: str | None, brand_color: str | None
) -> str:
    try:
        data, _ = frontmatter.load(skill_text)
    except ValueError:
        data = {}
    implicit = str(data.get("disable-model-invocation", "")).lower() != "true"
    short = short_description(str(data.get("description") or "")).replace('"', "'")
    lines = [
        "interface:",
        f"  display_name: {quote(display_name(name))}",
        f"  short_description: {quote(short)}",
    ]
    if icon:
        lines += [f"  icon_small: {quote(icon)}", f"  icon_large: {quote(icon)}"]
    if brand_color:
        lines.append(f"  brand_color: {quote(brand_color)}")
    lines += [
        "policy:",
        f"  allow_implicit_invocation: {'true' if implicit else 'false'}",
    ]
    return "\n".join(lines) + "\n"


def flat_skills(reg: Registry, overlay: Overlay) -> None:
    """``skills/<name>`` -> ``../plugins/<plugin>/skills/<name>`` for every skill."""
    wanted: dict[str, str] = {}
    for item in reg.items.items:
        for name in PluginBuild(reg, overlay, item).skill_names():
            target = f"../{plugin_dir(item.id)}/skills/{name}"
            if name in wanted and wanted[name] != target:
                raise InvalidInputError(
                    f"skill '{name}' exists in two plugins; the flat view needs "
                    "unique names"
                )
            wanted[name] = target
    root = reg.repo / FLAT_SKILLS_DIR
    if root.is_dir():
        for entry in root.iterdir():
            if entry.is_symlink() and entry.name not in wanted:
                overlay.remove(f"{FLAT_SKILLS_DIR}/{entry.name}")
    for name, target in sorted(wanted.items()):
        path = root / name
        if path.exists() and not path.is_symlink():
            raise InvalidInputError(
                f"{FLAT_SKILLS_DIR}/{name} is a real path; expected a generated link"
            )
        overlay.link(f"{FLAT_SKILLS_DIR}/{name}", target)


def main_ref(reg: Registry) -> str | None:
    """``origin/<main>`` when this checkout has it (CI may not)."""
    ref = f"origin/{reg.config.main_branch}"
    return ref if git.ref_exists(reg.repo, f"refs/remotes/{ref}") else None


def _head_or_zero(repo: Path) -> str:
    head = git.run(repo, "rev-parse", "--verify", "-q", "HEAD^{commit}", check=False)
    return head or "0" * 40


def local_files(
    reg: Registry, overlay: Overlay, item: Item, exclude: set[str]
) -> dict[str, FileLock]:
    """Lock entries of a local plugin's files, as they are with ``overlay``."""
    root = reg.repo / plugin_dir(item.id)
    ns = reg.config.namespace
    files = hashing.hash_tree(root, ns, exclude=exclude)
    for rel, old in list(files.items()):
        pending = overlay.pending.get(f"{plugin_dir(item.id)}/{rel}")
        if isinstance(pending, str | bytes) and old.mode != "120000":
            data = pending.encode() if isinstance(pending, str) else pending
            files[rel] = hashing.file_lock_for(rel, data, old.mode, ns)
    return files


def refresh_local(reg: Registry, overlay: Overlay, item: Item) -> None:
    """Lock the local plugin's current files (new skills, edits, version bumps)."""
    old = reg.lock.items.get(item.id)
    exclude = set(old.generated) if old else set()
    files = local_files(reg, overlay, item, exclude)
    tree = hashing.tree_sha256(files)
    if old is not None and not hashing.drift(old.files, files):
        return  # stamps alone are no change (normalized hashes)
    reg.lock.items[item.id] = ItemLock(
        kind=ItemKind.LOCAL,
        version=old.version if old else None,
        upstream=old.upstream.model_copy(update={"commit": _head_or_zero(reg.repo)})
        if old
        else Upstream(
            repository=reg.config.repository or reg.config.name,
            commit=_head_or_zero(reg.repo),
            path=plugin_dir(item.id),
        ),
        parts=old.parts if old else [],
        tree_sha256=tree,
        files=files,
        generated=sorted(exclude),
    )


def version_wanted(
    reg: Registry, item: Item, current: str | None, base: str, base_lock: LockFile
) -> str | None:
    """The version a changed local plugin needs, or None when it is fine."""
    lock = reg.lock.items.get(item.id)
    on_main = base_lock.items.get(item.id)
    if on_main is None:
        return None if current else versions.FIRST_VERSION
    if lock is not None and lock.tree_sha256 == on_main.tree_sha256:
        return None
    main_version = manifest_version_at(reg.repo, base, item.id)
    if versions.is_greater(current, main_version):
        return None
    if main_version is not None and versions.parse(main_version) is None:
        log.warning("Not bumping %s: version %s is not semver", item.id, main_version)
        return None
    return versions.bump(main_version)


def set_manifest_version(pb: PluginBuild, version: str) -> None:
    """Write ``version`` into every real manifest of the plugin (in the overlay)."""
    for path in pb.real_manifests() or [pb.source_manifest()]:
        full = pb.rel(path)
        text = pb.overlay.read_text(full)
        if text is not None:
            pb.overlay.write(full, versions.with_version(text, version))


def bump_local(
    reg: Registry,
    overlay: Overlay,
    item: Item,
    main: tuple[str, LockFile] | None,
) -> None:
    """Refresh the lock and give a changed local plugin its version bump."""
    refresh_local(reg, overlay, item)
    if main is None:
        return
    base, base_lock = main
    pb = PluginBuild(reg, overlay, item)
    current = version_of(overlay.read_text(pb.rel(pb.source_manifest())))
    wanted = version_wanted(reg, item, current, base, base_lock)
    if wanted is not None:
        log.info("Version of %s: %s -> %s", item.id, current, wanted)
        set_manifest_version(pb, wanted)
        refresh_local(reg, overlay, item)


def migrate(reg: Registry, overlay: Overlay) -> None:
    """Rewrite rev. 1 registry files (``bundle`` kind, staging channels, approvals)."""
    legacy = legacy_files(reg.repo)
    if ITEMS in legacy:
        overlay.write(
            f"{REGISTRY_DIR}/{ITEMS}", yaml_text(reg.repo, ITEMS, reg.items)[0]
        )
    if POLICY in legacy:
        overlay.write(
            f"{REGISTRY_DIR}/{POLICY}", yaml_text(reg.repo, POLICY, reg.policy)[0]
        )
    if LEGACY_APPROVALS in legacy:
        overlay.remove(f"{REGISTRY_DIR}/{LEGACY_APPROVALS}")


def plan(reg: Registry) -> Overlay:
    """Every change ``build`` would make, without touching the disk."""
    overlay = Overlay(reg.repo)
    migrate(reg, overlay)
    base = main_ref(reg)
    main = (base, model_at(reg.repo, base, LOCK, LockFile)) if base else None
    plugins: list[catalogs.CatalogPlugin] = []
    for item in sorted(reg.items.items, key=lambda i: i.id):
        if not (reg.repo / plugin_dir(item.id)).is_dir():
            log.warning("Item %s has no %s directory", item.id, plugin_dir(item.id))
            continue
        if item.kind is ItemKind.LOCAL:
            bump_local(reg, overlay, item, main)
        builder = PluginBuild(reg, overlay, item)
        builder.run()
        plugins.append(catalogs.CatalogPlugin(item, builder.manifest_data()))
        lock = reg.lock.items.get(item.id)
        if lock is not None:
            lock.generated = sorted(builder.created)
    if reg.config.layout.flat_skills:
        flat_skills(reg, overlay)
    overlay.write(catalogs.AGENTS_CATALOG, catalogs.agents_catalog(reg.config, plugins))
    overlay.write(catalogs.CLAUDE_CATALOG, catalogs.claude_catalog(reg.config, plugins))
    pin = reg.config.tool
    main = reg.config.main_branch
    write_workflow(
        overlay,
        pin,
        workflows.VALIDATE_WORKFLOW,
        lambda p: workflows.validate_workflow(p, main),
    )
    write_workflow(overlay, pin, workflows.SYNC_WORKFLOW, workflows.sync_workflow)
    overlay.write(f"{REGISTRY_DIR}/{LOCK}", render_lock(reg.lock))
    return overlay


def write_workflow(
    overlay: Overlay, pin: ToolPin, rel: str, render: Callable[[ToolPin], str]
) -> None:
    """Write a workflow unless it already runs the pinned skill-dojo.

    The template belongs to the skill-dojo that renders it, and CI runs the
    pinned one, so a newer local tool must not fight it over the same pin.
    """
    current = overlay.read_text(rel)
    if current is not None and f"{workflows.tool_command(pin)} " in current:
        log.debug("Keeping %s: it runs the pinned skill-dojo", rel)
        return
    overlay.write(rel, render(pin))


def apply_build(reg: Registry) -> list[str]:
    """Run ``build`` for real and return the changed paths."""
    overlay = plan(reg)
    changed = overlay.changes()
    overlay.apply()
    return changed
